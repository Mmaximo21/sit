export const FOODS: Food[] = ROWS.map((row, i) => {
  const [name, category, ...rest] = row;
  const values = rest.slice(0, KEYS.length) as number[];
  const unitLabel = row[22] as string | undefined;
  const unitGrams = row[23] as number | undefined;
  const nutrients = Object.fromEntries(
    KEYS.map((k, idx) => [k, values[idx] ?? 0]),
  ) as unknown as Nutrients;
  return {
    id: `f${i}`,
    name,
    category,
    ...(unitLabel && unitGrams ? { unit: { label: unitLabel, grams: unitGrams } } : {}),
    ...nutrients,
  };
});

